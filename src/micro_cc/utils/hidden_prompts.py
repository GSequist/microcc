def build(name: str, extra: str = "") -> str:
    """Wrap a prompt body into the hidden system-reminder turn."""
    return (
        "<system-reminder>\n"
        + PROMPT_BODIES[name]
        + (f"They also said: {extra}\n" if extra else "")
        + "</system-reminder>"
    )
