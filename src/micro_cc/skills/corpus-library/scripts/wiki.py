#!/usr/bin/env python3
"""Corpus library toolkit: manifest, assign, place, index, verify. Stdlib only; copied into <lib>/_meta/."""
import argparse, hashlib, json, os, posixpath, re, shutil, sys
from collections import Counter
from datetime import date
from pathlib import Path
from urllib.parse import quote

MAX_CHILDREN = 30
SKIP_FILES = {".DS_Store", "Thumbs.db"}
KEEP_DIRS = {"_meta", "_entities", "_inbox"}

README = """BUILD STATUS: pending
# @@NAME@@ — document library

> Read this file first. It says what this library is, how it is organised and how to maintain it.
> Everything needed is in this folder: `_meta/wiki.py` is the toolkit, no skill is required.
> Run commands from this folder: `python3 _meta/wiki.py <command>`.

## Purpose
@@PURPOSE@@

## Provenance
- Created @@DATE@@. Documents are COPIED into this tree; the originals were not moved.
- Never move or delete the original source folders: later "add docs" runs diff them against `_meta/manifest.jsonl`, and every doc's `orig_path` points back there.
<!-- stats:start --><!-- stats:end -->

## Tree
<!-- tree:start --><!-- tree:end -->

Each folder has an `_INDEX.md` (belongs-here rule + one line per doc). The rules live in `_meta/taxonomy.md`
as `path/ :: rule` lines and are the single source of truth for placement.

## How to traverse
1. This file -> pick the top-level folder whose rule fits.
2. That folder's `_INDEX.md` -> pick a subfolder or read the doc lines (title + summary).
3. Open the doc itself only when its summary is not enough.
Cross-cutting people / organisations / projects have pages in `_entities/` (see its `_INDEX.md`).
Free-text lookup: `grep -i <term> _meta/manifest.jsonl` searches every doc's title, summary, entities and tags.

## Conventions
- One primary home per doc (its folder). Relations across folders live in `_entities/*.md` and in prose links.
- Max ~@@MAX@@ children per folder; split when exceeded (see Rebalance).
- `_inbox/` holds docs that fit nowhere yet. Never invent a vague catch-all folder like `misc/`.
- `_INDEX.md`, the Tree and Provenance stats above are generated by `wiki.py index`; never hand-edit them.
- Summaries are one line: what the doc is and why it matters.

## Protocols
### Add docs
1. `python3 _meta/wiki.py scan --source <new-folder>` (omit `--source` to rescan known sources). Dedupes by sha256.
2. `python3 _meta/wiki.py todo` lists new docs. Read each, write `{"id","title","summary","entities":[],"tags":[]}` jsonl lines to `_meta/profiles/<batch>.jsonl` (parallel subagents: one file each), then `python3 _meta/wiki.py ingest`.
3. Choose buckets using `_meta/taxonomy.md`: `wiki.py assign --match REGEX --bucket path` for bulk, or `ingest` jsonl lines `{"id","bucket"}`. No fit -> `_inbox`. A genuinely new bucket: add a `path/ :: rule` line to taxonomy.md, keep `approved: yes`, and tell the user.
4. `python3 _meta/wiki.py place`, then `index`, then `finish` (runs `verify`). Append a line to `_meta/log.md` for any manual decision.

### Answer a question
Traverse as above; use `grep` on `manifest.jsonl` to jump; cite the doc's `lib_path`. Do not scan every file.

### Rebalance
When `verify` warns about a folder over the limit or `_inbox/` grows: propose a split to the user (new `path/ :: rule` lines), and only after approval re-assign (`assign` / `ingest` with a new `bucket`), `place` (moves files), `index`, `finish`.

### Resume an interrupted build
Line 1 of this file shows the phase. Run `python3 _meta/wiki.py status`; it prints state and the next command. Every step is idempotent.

## Files
- `_meta/manifest.jsonl` one row per unique doc: id, sha, orig_path, also_at, status (scanned > profiled > placed), title, summary, entities, tags, bucket, lib_path.
- `_meta/taxonomy.md` the tree rules + `approved: yes|no`. `_meta/log.md` append-only history. `_meta/config.json` sources and state.
"""

TAXONOMY = """# Taxonomy

approved: no

Rules, one per line: `path/ :: what belongs here (and what does not)`. Up to 3 levels, max ~30 children per folder.
Always keep `_inbox/ :: docs that fit nowhere yet`.

- _inbox/ :: docs that fit nowhere yet
"""


def load_rows(lib):
    p = lib / "_meta" / "manifest.jsonl"
    if not p.exists():
        return {}
    return {r["id"]: r for r in (json.loads(l) for l in p.read_text().splitlines() if l.strip())}


def save_rows(lib, rows):
    p = lib / "_meta" / "manifest.jsonl"
    tmp = p.with_suffix(".tmp")
    tmp.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows.values()))
    tmp.replace(p)


def load_cfg(lib):
    return json.loads((lib / "_meta" / "config.json").read_text())


def save_cfg(lib, cfg):
    (lib / "_meta" / "config.json").write_text(json.dumps(cfg, indent=2))


def log(lib, msg):
    with open(lib / "_meta" / "log.md", "a") as f:
        f.write(f"- {date.today()} {msg}\n")


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_taxonomy(lib):
    t = (lib / "_meta" / "taxonomy.md").read_text()
    approved = bool(re.search(r"^approved:\s*yes\b", t, re.M | re.I))
    rules = {m[1].strip("/"): m[2].strip() for m in re.finditer(r"^\s*[-*]?\s*`?([^\s`:]+)/`?\s*::\s*(.+)$", t, re.M)}
    return approved, rules


def clean_bucket(b):
    b = posixpath.normpath(str(b).strip().strip("/"))
    if b in (".", "") or b.startswith("..") or "/../" in b or b.split("/")[0] == "_meta":
        raise ValueError(f"bad bucket {b!r}")
    return b


def parent_of(r):
    return str(Path(r["lib_path"]).parent)


def compute_phase(lib, rows, cfg):
    cnt = Counter(r["status"] for r in rows.values())
    approved, _ = read_taxonomy(lib)
    unassigned = sum(1 for r in rows.values() if r["status"] == "profiled" and not r.get("bucket"))
    to_place = sum(1 for r in rows.values() if (r["status"] == "profiled" and r.get("bucket"))
                   or (r["status"] == "placed" and r.get("bucket") and r["bucket"] != parent_of(r)))
    if not rows:
        return 1, "scan", "python3 _meta/wiki.py scan --source <folder>"
    if cnt["scanned"]:
        return 2, "profile", "`wiki.py todo`, read docs, write _meta/profiles/*.jsonl, `wiki.py ingest`"
    if not approved:
        return 3, "taxonomy", "draft _meta/taxonomy.md, show the user, set 'approved: yes' only after they agree"
    if unassigned or to_place:
        return 4, "assign+place", f"{unassigned} docs need a bucket (`wiki.py assign` / `ingest`); then `wiki.py place`"
    if not cfg.get("complete"):
        return 5, "index+verify", "`wiki.py index`, then `wiki.py finish`"
    return 6, "complete", "nothing pending"


def refresh(lib, rows=None):
    rows = rows if rows is not None else load_rows(lib)
    cfg = load_cfg(lib)
    n, name, nxt = compute_phase(lib, rows, cfg)
    if n == 6:
        line = f"BUILD STATUS: COMPLETE ({cfg['complete']}, {sum(1 for r in rows.values() if r['status'] == 'placed')} docs)"
    else:
        line = f"BUILD STATUS: IN PROGRESS, phase {n}/5 ({name}). Next: {nxt}. State: `python3 _meta/wiki.py status`."
    p = lib / "README.md"
    lines = p.read_text().split("\n")
    lines[0] = line
    p.write_text("\n".join(lines))


def replace_block(text, name, body):
    return re.sub(rf"(<!-- {name}:start -->).*?(<!-- {name}:end -->)", lambda m: f"{m[1]}\n{body}\n{m[2]}", text, flags=re.S)


def render_indexes(lib, rows, rules):
    placed = [r for r in rows.values() if r["status"] == "placed"]
    dirs = set()
    for r in placed:
        parts = Path(r["lib_path"]).parent.parts
        dirs |= {"/".join(parts[:i]) for i in range(1, len(parts) + 1)}
    count = lambda d: sum(1 for r in placed if parent_of(r) == d or parent_of(r).startswith(d + "/"))
    out = {}
    for d in sorted(dirs):
        parent_link = "../README.md" if "/" not in d else "../_INDEX.md"
        lines = [f"# {d}/", "", f"Rule: {rules.get(d, '(no rule in taxonomy.md)')}", "",
                 f"Docs: {count(d)} · Parent: [{parent_link}]({parent_link})", ""]
        subs = sorted(x for x in dirs if str(Path(x).parent) == d)
        if subs:
            lines += ["## Subfolders"] + [f"- [{Path(s).name}/]({quote(Path(s).name)}/_INDEX.md) — {rules.get(s, '')} — {count(s)} docs" for s in subs] + [""]
        docs = sorted((r for r in placed if parent_of(r) == d), key=lambda r: r["lib_path"])
        if docs:
            lines += ["## Docs"] + [f"- [{Path(r['lib_path']).name}]({quote(Path(r['lib_path']).name)}) — **{r.get('title', '')}** — {r.get('summary', '')}" for r in docs] + [""]
        out[f"{d}/_INDEX.md"] = "\n".join(lines)
    ent = lib / "_entities"
    if ent.is_dir():
        pages = sorted(p for p in ent.glob("*.md") if p.name != "_INDEX.md")
        items = []
        for p in pages:
            h = next((l.lstrip("# ").strip() for l in p.read_text().splitlines() if l.strip()), p.stem)
            items.append(f"- [{p.name}]({quote(p.name)}) — {h}")
        out["_entities/_INDEX.md"] = "\n".join(["# _entities/", "", "Cross-cutting people / organisations / projects. One page each, linking the docs involved.", ""] + items + [""])
    return out


def cmd_init(a):
    lib = Path(a.lib).expanduser().resolve()
    if (lib / "_meta").exists():
        sys.exit(f"{lib} already initialised; use scan/status")
    for d in ("_meta/profiles", "_inbox", "_entities"):
        (lib / d).mkdir(parents=True, exist_ok=True)
    readme = README.replace("@@NAME@@", lib.name).replace("@@PURPOSE@@", a.purpose).replace("@@DATE@@", str(date.today())).replace("@@MAX@@", str(MAX_CHILDREN))
    (lib / "README.md").write_text(readme)
    (lib / "_meta" / "taxonomy.md").write_text(TAXONOMY)
    (lib / "_meta" / "log.md").write_text("# Log\n\n")
    save_cfg(lib, {"sources": [], "created": str(date.today()), "complete": None})
    shutil.copy2(__file__, lib / "_meta" / "wiki.py")
    log(lib, f"init, purpose: {a.purpose}")
    a.lib = str(lib)
    cmd_scan(a)


def cmd_scan(a):
    lib = Path(a.lib)
    cfg = load_cfg(lib)
    for s in a.source or []:
        s = str(Path(s).expanduser().resolve())
        if s not in cfg["sources"]:
            cfg["sources"].append(s)
    rows = load_rows(lib)
    known = {}
    for r in rows.values():
        known[r["orig_path"]] = r
        for p in r["also_at"]:
            known[p] = r
    new = dup = 0
    for src in cfg["sources"]:
        for root, dnames, fnames in os.walk(src):
            dnames[:] = [d for d in dnames if not d.startswith(".") and Path(root, d).resolve() != lib]
            for fn in fnames:
                if fn in SKIP_FILES or fn.startswith((".", "~$")):
                    continue
                p = Path(root, fn)
                st = p.stat()
                k = known.get(str(p))
                if k and (str(p) in k["also_at"] or (k["bytes"] == st.st_size and k["mtime"] == st.st_mtime_ns)):
                    continue
                h = sha256(p)
                rid = h[:16]
                if rid in rows:
                    if str(p) not in rows[rid]["also_at"] and str(p) != rows[rid]["orig_path"]:
                        rows[rid]["also_at"].append(str(p))
                    dup += 1
                    continue
                rows[rid] = {"id": rid, "sha": h, "orig_path": str(p), "also_at": [], "bytes": st.st_size, "mtime": st.st_mtime_ns,
                             "ext": p.suffix.lower(), "status": "scanned"}
                known[str(p)] = rows[rid]
                new += 1
    save_rows(lib, rows)
    if new:
        cfg["complete"] = None
    save_cfg(lib, cfg)
    log(lib, f"scan: {new} new, {dup} duplicates, sources={cfg['sources']}")
    refresh(lib, rows)
    print(f"scan: {new} new docs, {dup} duplicates, {len(rows)} unique total")


def cmd_status(a):
    lib = Path(a.lib)
    rows, cfg = load_rows(lib), load_cfg(lib)
    n, name, nxt = compute_phase(lib, rows, cfg)
    print(f"phase {n}/5 {name} · next: {nxt}" if n < 6 else f"COMPLETE {cfg['complete']}")
    print("status:", dict(Counter(r["status"] for r in rows.values())))
    print("approved:", read_taxonomy(lib)[0], "· sources:", cfg["sources"])
    print("ext:", dict(Counter(r["ext"] for r in rows.values()).most_common(12)))
    print("tags:", dict(Counter(t for r in rows.values() for t in r.get("tags", [])).most_common(30)))
    print("buckets:", dict(Counter(r.get("bucket") for r in rows.values() if r.get("bucket")).most_common(40)))
    print("profiles pending ingest:", len(list((lib / "_meta" / "profiles").glob("*.jsonl"))))


def cmd_todo(a):
    rows = load_rows(Path(a.lib))
    sel = [r for r in rows.values() if r["status"] == a.status and (not a.unassigned or not r.get("bucket"))]
    for r in sel[a.offset:a.offset + a.limit]:
        print(json.dumps({k: r.get(k) for k in ("id", "orig_path", "bytes", "ext", "title", "summary", "tags", "bucket") if r.get(k) not in (None, "", [])}, ensure_ascii=False))
    print(f"# {len(sel)} total with status={a.status}; showing {a.offset}-{min(a.offset + a.limit, len(sel))}", file=sys.stderr)


def cmd_ingest(a):
    lib = Path(a.lib)
    rows = load_rows(lib)
    pdir = lib / "_meta" / "profiles"
    files = [Path(f) for f in a.files] or sorted(pdir.glob("*.jsonl"))
    n = bad = 0
    for f in files:
        for line in f.read_text().splitlines():
            if not line.strip():
                continue
            d = json.loads(line)
            r = rows.get(d.get("id"))
            if not r:
                bad += 1
                print(f"unknown id in {f.name}: {d.get('id')}")
                continue
            for k in ("title", "summary", "entities", "tags"):
                if k in d:
                    r[k] = " ".join(d[k].split()) if isinstance(d[k], str) else d[k]
            if d.get("bucket"):
                try:
                    r["bucket"] = clean_bucket(d["bucket"])
                except ValueError as e:
                    bad += 1
                    print(f"{d['id']}: {e}")
            if r["status"] == "scanned" and r.get("title") and r.get("summary"):
                r["status"] = "profiled"
            n += 1
        if f.parent == pdir:
            (pdir / "done").mkdir(exist_ok=True)
            f.replace(pdir / "done" / f.name)
    save_rows(lib, rows)
    log(lib, f"ingest: {n} rows from {len(files)} files, {bad} errors")
    refresh(lib, rows)
    print(f"ingested {n} rows, {bad} errors")


def cmd_assign(a):
    lib = Path(a.lib)
    rows = load_rows(lib)
    bucket = clean_bucket(a.bucket)
    rx = re.compile(a.match, re.I) if a.match else None
    n = 0
    for r in rows.values():
        if r["status"] == "scanned" or (r.get("bucket") and not a.override):
            continue
        hay = " ".join([r["orig_path"], r.get("title", ""), r.get("summary", ""), " ".join(r.get("tags", [])), " ".join(r.get("entities", []))])
        if (rx and not rx.search(hay)) or (a.tag and a.tag not in r.get("tags", [])) or (a.ext and r["ext"] != a.ext):
            continue
        r["bucket"] = bucket
        n += 1
    save_rows(lib, rows)
    log(lib, f"assign: {n} docs -> {bucket} (match={a.match} tag={a.tag} ext={a.ext})")
    refresh(lib, rows)
    print(f"assigned {n} docs -> {bucket}")


def cmd_place(a):
    lib = Path(a.lib)
    approved, _ = read_taxonomy(lib)
    if not approved:
        sys.exit("taxonomy.md is not approved: show the user the tree and set 'approved: yes' first")
    rows = load_rows(lib)
    placed = moved = missing = 0
    for i, r in enumerate(rows.values()):
        if not r.get("bucket"):
            continue
        name = Path(r["orig_path"]).name
        if r["status"] == "profiled":
            src = Path(r["orig_path"])
            if not src.exists():
                missing += 1
                print(f"SOURCE MISSING: {src}")
                continue
        elif r["status"] == "placed" and r["bucket"] != parent_of(r):
            src = lib / r["lib_path"]
            name = src.name
        else:
            continue
        dest_dir = lib / r["bucket"]
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / name
        if dest.exists() and dest != src and sha256(dest) != r["sha"]:
            dest = dest_dir / f"{Path(name).stem}-{r['id'][:8]}{Path(name).suffix}"
        if r["status"] == "profiled":
            if not (dest.exists() and sha256(dest) == r["sha"]):
                shutil.copy2(src, dest)
            placed += 1
        else:
            if dest != src:
                shutil.move(src, dest)
            moved += 1
        r["status"], r["lib_path"] = "placed", str(dest.relative_to(lib))
        if i % 200 == 199:
            save_rows(lib, rows)
    save_rows(lib, rows)
    log(lib, f"place: {placed} copied, {moved} moved, {missing} source-missing")
    refresh(lib, rows)
    print(f"placed {placed}, moved {moved}, missing sources {missing}")


def cmd_index(a):
    lib = Path(a.lib)
    rows = load_rows(lib)
    cfg = load_cfg(lib)
    _, rules = read_taxonomy(lib)
    out = render_indexes(lib, rows, rules)
    for rel, text in out.items():
        (lib / rel).write_text(text)
    for p in lib.rglob("_INDEX.md"):
        if str(p.relative_to(lib)) not in out and p.relative_to(lib).parts[0] != "_meta":
            p.unlink()
    for d in sorted((p for p in lib.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
        top = d.relative_to(lib).parts[0]
        if top not in KEEP_DIRS and not any(d.iterdir()):
            d.rmdir()
    placed = [r for r in rows.values() if r["status"] == "placed"]
    top = Counter(r["lib_path"].split("/")[0] for r in placed if "/" in r["lib_path"])
    tree = []
    for d in sorted(x for x in rules if x.count("/") <= 1):
        n = sum(1 for r in placed if r["lib_path"].startswith(d + "/"))
        tree.append(f"{'  ' * d.count('/')}- `{d}/` ({n} docs) — {rules[d]}")
    stats = [f"- Docs in library: {len(placed)} (unique); sources: " + ", ".join(f"`{s}`" for s in cfg["sources"]),
             f"- Index regenerated: {date.today()}"]
    t = (lib / "README.md").read_text()
    t = replace_block(t, "tree", "\n".join(tree) or "(no folders yet)")
    (lib / "README.md").write_text(replace_block(t, "stats", "\n".join(stats)))
    refresh(lib, rows)
    print(f"indexed {len(out)} folders")


def verify(lib, rows):
    errs, warns = [], []
    approved, rules = read_taxonomy(lib)
    known = {r["lib_path"] for r in rows.values() if r["status"] == "placed"}
    for r in rows.values():
        if r["status"] == "placed":
            p = lib / r["lib_path"]
            if not p.exists():
                errs.append(f"missing file: {r['lib_path']}")
            elif sha256(p) != r["sha"]:
                errs.append(f"sha mismatch: {r['lib_path']}")
            if not r.get("title") or not r.get("summary"):
                errs.append(f"no title/summary: {r['lib_path']}")
        else:
            errs.append(f"not placed ({r['status']}): {r['orig_path']}")
    skip_names = {"_INDEX.md"}
    for p in lib.rglob("*"):
        rel = p.relative_to(lib)
        if p.is_file() and rel.parts[0] != "_meta" and rel.parts[0] != "_entities" and str(rel) != "README.md" and p.name not in skip_names and str(rel) not in known:
            errs.append(f"file not in manifest: {rel}")
        if p.is_dir() and rel.parts[0] not in ("_meta",):
            n = len(list(p.iterdir())) - (1 if (p / "_INDEX.md").exists() else 0)
            if n > MAX_CHILDREN:
                warns.append(f"{rel}/ has {n} children (> {MAX_CHILDREN}): propose a split")
    for rel, text in render_indexes(lib, rows, rules).items():
        if not (lib / rel).exists() or (lib / rel).read_text() != text:
            errs.append(f"stale index: {rel} (run wiki.py index)")
    if not approved:
        errs.append("taxonomy not approved")
    inbox = sum(1 for r in rows.values() if r.get("bucket") == "_inbox")
    if inbox:
        warns.append(f"_inbox has {inbox} docs: place them or propose a bucket")
    return errs, warns


def cmd_verify(a):
    lib = Path(a.lib)
    errs, warns = verify(lib, load_rows(lib))
    for e in errs:
        print("ERROR", e)
    for w in warns:
        print("WARN ", w)
    print(f"verify: {len(errs)} errors, {len(warns)} warnings")
    return len(errs)


def cmd_finish(a):
    lib = Path(a.lib)
    rows = load_rows(lib)
    errs, warns = verify(lib, rows)
    if errs:
        for e in errs[:30]:
            print("ERROR", e)
        sys.exit(f"cannot finish: {len(errs)} errors")
    cfg = load_cfg(lib)
    cfg["complete"] = str(date.today())
    save_cfg(lib, cfg)
    log(lib, f"finish: complete, {len(rows)} docs, {len(warns)} warnings")
    refresh(lib, rows)
    for w in warns:
        print("WARN ", w)
    print("COMPLETE. Remind the user: do not move or delete the original source folders.")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lib", help="library folder (default: parent of this script's _meta/)")
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("init"); p.add_argument("--source", action="append", required=True); p.add_argument("--purpose", required=True)
    p = sp.add_parser("scan"); p.add_argument("--source", action="append")
    sp.add_parser("status")
    p = sp.add_parser("todo"); p.add_argument("--status", default="scanned"); p.add_argument("--limit", type=int, default=40); p.add_argument("--offset", type=int, default=0); p.add_argument("--unassigned", action="store_true")
    p = sp.add_parser("ingest"); p.add_argument("files", nargs="*")
    p = sp.add_parser("assign"); p.add_argument("--bucket", required=True); p.add_argument("--match"); p.add_argument("--tag"); p.add_argument("--ext"); p.add_argument("--override", action="store_true")
    for c in ("place", "index", "verify", "finish"):
        sp.add_parser(c)
    a = ap.parse_args()
    if not a.lib:
        here = Path(__file__).resolve().parent
        if here.name != "_meta":
            sys.exit("pass --lib <folder>")
        a.lib = str(here.parent)
    a.lib = str(Path(a.lib).expanduser().resolve())
    sys.exit(globals()[f"cmd_{a.cmd}"](a) or 0)


if __name__ == "__main__":
    main()
